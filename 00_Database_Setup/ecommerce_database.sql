SELECT 'Users' AS TableName, COUNT(*) AS TotalRecords
FROM dbo.Users
UNION ALL
SELECT 'Products', COUNT(*)
FROM dbo.Products
UNION ALL
SELECT 'Orders', COUNT(*)
FROM dbo.Orders;
GO

SELECT u.UserID, u.FirstName, u.LastName, COUNT(o.OrderID) AS TotalOrders
FROM dbo.Users AS u
    LEFT JOIN dbo.Orders AS o ON u.UserID = o.UserID
GROUP BY
    u.UserID,
    u.FirstName,
    u.LastName
ORDER BY u.UserID;
GO

